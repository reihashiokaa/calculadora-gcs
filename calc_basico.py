def somar(a, b):
    """Retorna a soma de a e b."""
    return a + b

def subtrair(a, b):
    """Retorna a diferença entre a e b."""
    return a - b

def multiplicar(a, b):
    """Retorna o produto entre a e b."""
    return a * b